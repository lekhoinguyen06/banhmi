import fs from "fs";
import path from "path";

interface BanhMiProps {
  srcDir: string;
  outDir?: string;
  prefix?: string;
  extension?: string;
}

interface BanhMiType<D extends string, V extends string> {
  PAGE(domain: D, metadata: BaseMetadata<D, V>): void;
  TEXT(text: string, metadata?: BaseMetadata<D, V>): void;
  CODE(
    code: string,
    metadata?: BaseMetadata<D, V> & { language?: string },
  ): void;
  TABLE(
    table: { columns: string[]; rows: string[][] },
    metadata?: BaseMetadata<D, V>,
  ): void;
  FRONTMATTER(
    frontmatter: Record<string, string>,
    metadata?: BaseMetadata<D, V>,
  ): void;
  write(): Promise<void>;
}

interface PageType<D extends string, V extends string> {
  content: string;
  metadata?: BaseMetadata<D, V>;
}

interface ViewPageType {
  content: string;
}

interface BaseMetadata<D extends string, V extends string> {
  domainRefs?: D[];
  viewRefs?: V[];
}

function appendBlockToPage<D extends string, V extends string>({
  pages,
  viewPages,
  currentDomain,
  content,
  metadata,
}: {
  pages: Map<string, PageType<D, V>>;
  viewPages: Map<string, ViewPageType>;
  currentDomain?: string;
  content?: string;
  metadata?: BaseMetadata<D, V>;
}): void {
  if (!currentDomain) {
    throw new Error(
      "Current domain is not defined. Please use PAGE at the top of your file module.",
    );
  }

  if (!content) {
    return;
  }

  const existingPage = pages.get(currentDomain);

  if (existingPage) {
    pages.set(currentDomain, {
      content: existingPage.content.concat(content),
      metadata: { ...existingPage.metadata, ...metadata },
    });
  } else {
    pages.set(currentDomain, { content, metadata });
  }

  if (metadata?.viewRefs) {
    for (const viewRef of metadata.viewRefs) {
      const existingViewPage = viewPages.get(viewRef);

      if (existingViewPage) {
        viewPages.set(viewRef, {
          content: existingViewPage.content.concat(content),
        });
      } else {
        viewPages.set(viewRef, { content });
      }
    }
  }
}

export function getBanhMi<D extends string, V extends string>({
  srcDir,
  outDir = "./banhmi/generated",
  prefix = "mi_",
  extension = ".mi.ts",
}: BanhMiProps): BanhMiType<D, V> {
  const viewPages: Map<string, ViewPageType> = new Map();
  const pages: Map<string, PageType<D, V>> = new Map();
  let currentDomain: D | undefined = undefined;
  return {
    PAGE(domain: D, metadata: BaseMetadata<D, V>): void {
      const headMsg = `\n\n<!-- [Bánh Mì compiler message: This file is auto generated by Bánh Mì, any edit over will be overwritten.] -->\n`;
      pages.set(domain, { content: `# ${domain}${headMsg}`, metadata });
      currentDomain = domain;
    },
    TEXT(text: string, metadata?: BaseMetadata<D, V>): void {
      appendBlockToPage({
        pages,
        viewPages,
        currentDomain,
        content: text,
        metadata,
      });
    },
    CODE(
      code: string,
      metadata?: BaseMetadata<D, V> & { language?: string },
    ): void {
      const codeContent = `\n\n\`\`\`${metadata?.language}\n${code}\n\`\`\`\n\n`;
      appendBlockToPage({
        pages,
        viewPages,
        currentDomain,
        content: codeContent,
        metadata,
      });
    },
    TABLE(
      table: { columns: string[]; rows: string[][] },
      metadata?: BaseMetadata<D, V>,
    ): void {
      const tableHeader = `| ${table.columns.join(" | ")} |\n| ${table.columns.map(() => "---").join(" | ")} |\n`;
      const tableRows = table.rows
        .map((row) => `| ${row.join(" | ")} |`)
        .join("\n");
      const tableContent = `${tableHeader}${tableRows}\n`;
      appendBlockToPage({
        pages,
        viewPages,
        currentDomain,
        content: tableContent,
        metadata,
      });
    },
    FRONTMATTER(
      frontmatter: Record<string, string>,
      metadata?: BaseMetadata<D, V>,
    ): void {
      const fontmatterContent = `---\n${Object.entries(frontmatter)
        .map(([key, value]) => `${key}: ${value}`)
        .join("\n")}\n---\n`;
      appendBlockToPage({
        pages,
        viewPages,
        currentDomain,
        content: fontmatterContent,
        metadata,
      });
    },
    async write(): Promise<void> {
      console.log(`Baking...`);
      // Traverse all files with the extension & load the module to inject the content

      async function load(directory: string, extension: string): Promise<void> {
        for (const entry of fs.readdirSync(directory, {
          withFileTypes: true,
        })) {
          const entryPath = path.join(directory, entry.name);

          if (entry.isDirectory()) {
            await load(entryPath, extension);
          } else if (entry.isFile() && entry.name.endsWith(extension)) {
            await import(entryPath);
            console.log(`Loaded: ${entryPath}`);
          }
        }
      }

      await load(srcDir, extension);

      let tsOuput = "";

      for (const [domain, page] of pages.entries()) {
        let outputContent = page.content;

        // Domain references: If a page has domainRefs, we will append the content of the referenced domains to the current page
        if (page.metadata?.domainRefs) {
          for (const [otherDomain, otherPage] of pages.entries()) {
            if (page.metadata.domainRefs.includes(otherDomain as D)) {
              const refMsg = `\n\n<!-- [Bánh Mì compiler message: Referenced from domain: ${otherDomain}] -->\n`;
              const endRefMsg = `\n<!-- [Bánh Mì compiler message: End of reference from domain: ${otherDomain}] -->\n\n`;
              const refContent = `${refMsg}\n${otherPage.content}\n${endRefMsg}\n`;
              outputContent = outputContent.concat(refContent);
            }
          }
        }

        const outputFileName = `${prefix}${domain}$${outputContent.length}.md`;
        const outputFilePath = path.join(outDir, outputFileName);
        fs.mkdirSync(outDir, { recursive: true });
        fs.writeFileSync(outputFilePath, outputContent);
        tsOuput += `export const ${prefix}${domain}$${outputContent.length} = ${JSON.stringify(outputContent)};\n`;
      }

      for (const [domain, page] of viewPages.entries()) {
        let outputContent = page.content;

        const outputFileName = `${prefix}${domain}$${outputContent.length}.md`;
        const outputFilePath = path.join(outDir, outputFileName);
        fs.mkdirSync(outDir, { recursive: true });
        fs.writeFileSync(outputFilePath, outputContent);
        tsOuput += `export const ${prefix}${domain}$${outputContent.length} = ${JSON.stringify(outputContent)};\n`;
      }

      const tsOutputPath = path.join(outDir, "index.ts");
      fs.writeFileSync(tsOutputPath, tsOuput);

      console.log(`Baked ${pages.size} 🍞 into ${outDir}`);
    },
  };
}
